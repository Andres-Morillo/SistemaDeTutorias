create table if not exists public.tutorias (
  id bigint generated by default as identity primary key,
  materia text not null check (length(btrim(materia)) > 0),
  curso text not null check (length(btrim(curso)) > 0),
  dia text not null check (length(btrim(dia)) > 0),
  horario text not null check (length(btrim(horario)) > 0)
);

alter table public.tutorias enable row level security;

grant select on table public.tutorias to authenticated;

drop policy if exists "Usuarios autenticados pueden consultar tutorias"
on public.tutorias;

create policy "Usuarios autenticados pueden consultar tutorias"
on public.tutorias
for select
to authenticated
using (true);

insert into public.tutorias (materia, curso, dia, horario)
select 'Robótica', '4°', 'Lunes', '08:00 - 08:40'
where not exists (
  select 1
  from public.tutorias
  where materia = 'Robótica'
    and curso = '4°'
    and dia = 'Lunes'
    and horario = '08:00 - 08:40'
);
